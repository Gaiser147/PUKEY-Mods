REPOSITORY = "Gaiser147/PUKEY-Mods"
MAX_DOWNLOAD = 128 * 1024 * 1024
MAX_FILE = 32 * 1024 * 1024
MAX_EXPANDED = 256 * 1024 * 1024
KEYS = {"F%d" % n for n in range(1, 13)} | set("ABCDEFGHIJKLMNOPQRSTUVWXYZ") | {
    "HOME", "END", "PAGE_UP", "PAGE_DOWN", "INSERT", "DELETE", "SPACE",
    "ONE", "TWO", "THREE", "FOUR", "FIVE", "SIX", "SEVEN", "EIGHT", "NINE", "ZERO"}


def is_redirect(path):
    """Reject reparse points on every supported Python, including pre-3.12 Windows."""
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return False
    return stat.S_ISLNK(info.st_mode) or bool(
        getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))


def safe_path(value):
    if not isinstance(value, str) or not value or "\\" in value or ":" in value or "\x00" in value:
        raise ValueError("Invalid relative path: %r" % value)
    parts = value.split("/")
    if any(p in ("", ".", "..") or p.endswith((" ", ".")) or any(ord(c) < 32 for c in p)
           or re.match(r"^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)", p, re.I) for p in parts):
        raise ValueError("Unsafe relative path: %r" % value)
    return value


def _object_pairs(pairs):
    output = {}
    for key, value in pairs:
        if key in output: raise ValueError("Duplicate JSON key: " + key)
        output[key] = value
    return output


def parse_json(data):
    try:
        return json.loads(data, object_pairs_hook=_object_pairs,
                          parse_constant=lambda value: (_ for _ in ()).throw(ValueError("Non-finite JSON")))
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError("Malformed JSON: " + str(exc)) from exc


def validate_settings(mod, values):
    if not isinstance(values, dict): raise ValueError("Settings must be an object")
    specs = mod.get("settings", [])
    allowed = {s["key"] for s in specs}
    if set(values) - allowed: raise ValueError("Unknown setting: " + str(set(values) - allowed))
    result = {}
    for spec in specs:
        key = spec["key"]; value = values.get(key, spec["default"]); kind = spec["type"]
        valid = False
        if kind == "boolean": valid = type(value) is bool
        elif kind == "number":
            valid = type(value) in (int, float) and math.isfinite(value) and spec["min"] <= value <= spec["max"]
        elif kind == "enum": valid = isinstance(value, str) and value in spec["options"]
        elif kind == "key": valid = isinstance(value, str) and value in KEYS
        if not valid: raise ValueError("Invalid value for setting " + key)
        result[key] = value
    return result


def _lua_string(value):
    # Decimal byte escapes have exactly three digits, so adjacent digits are unambiguous.
    return '"' + ''.join('\\%03d' % b if b < 32 or b >= 127 else '\\' + chr(b) if b in (34, 92) else chr(b)
                         for b in value.encode("utf-8")) + '"'


def lua_settings(values):
    lines = ["-- Generated by PUKEY Mod Manager. Restart the game after changes.", "return {"]
    for key, value in values.items():
        if not isinstance(key, str): raise ValueError("Setting keys must be strings")
        if isinstance(value, str): rendered = _lua_string(value)
        elif type(value) is bool: rendered = "true" if value else "false"
        elif type(value) in (int, float) and math.isfinite(value): rendered = repr(value)
        else: raise ValueError("Unsupported Lua setting value")
        lines.append("    [%s] = %s," % (_lua_string(key), rendered))
    return ("\n".join(lines) + "\n}\n").encode("utf-8")


def _catalogue(data):
    catalog = parse_json(data)
    if not isinstance(catalog, dict) or type(catalog.get("schema_version")) is not int or catalog["schema_version"] != 1:
        raise ValueError("Unsupported catalogue schema. Update the manager.")
    if set(catalog) - {"schema_version", "mods"}: raise ValueError("Unsupported catalogue features. Update the manager.")
    mods = catalog.get("mods")
    if not isinstance(mods, list): raise ValueError("Catalogue mods must be an array")
    ids = set()
    for mod in mods:
        if not isinstance(mod, dict): raise ValueError("Invalid mod entry")
        if set(mod) - {"id", "name", "version", "description", "controls", "files", "settings", "images", "video_list", "video_folder"}:
            raise ValueError("Unsupported mod features. Update the manager.")
        name = mod.get("id")
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{0,63}", name): raise ValueError("Unsafe mod ID")
        safe_path(name)
        if name.casefold() in ids: raise ValueError("Duplicate mod ID")
        ids.add(name.casefold())
        for field in ("name", "version", "description", "controls"):
            if not isinstance(mod.get(field), str): raise ValueError("Missing text field " + field)
        files = mod.get("files")
        if not isinstance(files, list) or "Scripts/main.lua" not in files: raise ValueError("Missing Scripts/main.lua")
        seen = set()
        for path in files:
            safe_path(path)
            if path.casefold() in seen or PurePosixPath(path).name.casefold() in ("settings.lua", "settings.json", "enabled.txt"):
                raise ValueError("Conflicting or user-owned payload: " + path)
            seen.add(path.casefold())
        specs = mod.get("settings", [])
        if not isinstance(specs, list): raise ValueError("Settings must be an array")
        settings_keys = set()
        for spec in specs:
            if not isinstance(spec, dict) or not isinstance(spec.get("key"), str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", spec["key"]):
                raise ValueError("Invalid setting key")
            if spec["key"] in settings_keys or spec.get("type") not in ("boolean", "number", "enum", "key") or "default" not in spec:
                raise ValueError("Invalid or duplicate setting")
            settings_keys.add(spec["key"])
            if not isinstance(spec.get("label"), str): raise ValueError("Missing setting label")
            if spec["type"] == "number":
                for field in ("min", "max"):
                    if type(spec.get(field)) not in (int, float) or not math.isfinite(spec[field]): raise ValueError("Invalid number bounds")
                if spec["min"] > spec["max"]: raise ValueError("Invalid number bounds")
                if "step" in spec and (type(spec["step"]) not in (int, float) or not math.isfinite(spec["step"]) or spec["step"] <= 0): raise ValueError("Invalid step")
            if spec["type"] == "enum" and (not isinstance(spec.get("options"), list) or not spec["options"] or any(not isinstance(v, str) for v in spec["options"]) or len(set(spec["options"])) != len(spec["options"])):
                raise ValueError("Invalid enum options")
        validate_settings(mod, {})
        images = mod.get("images", [])
        if not isinstance(images, list): raise ValueError("Images must be an array")
        for image in images:
            if not isinstance(image, dict): raise ValueError("Invalid image")
            safe_path(image.get("file"))
            if PurePosixPath(image["file"]).suffix.lower() != ".png": raise ValueError("Image targets must be PNG files")
            if image["file"].casefold() in seen: raise ValueError("Image conflicts with shipped payload")
            seen.add(image["file"].casefold())
            if not isinstance(image.get("label"), str) or image.get("background") not in ("transparent", "green"):
                raise ValueError("Invalid image specification")
            for field in ("width", "height"):
                if type(image.get(field)) is not int or not 1 <= image[field] <= 8192: raise ValueError("Invalid image size")
            if image['width'] * image['height'] > 16_000_000: raise ValueError('Image exceeds 16 million pixels')
            for field, default in (("scale", 100), ("top", 0)):
                value = image.get(field, default)
                if type(value) not in (int, float) or not math.isfinite(value): raise ValueError("Invalid image layout")
                low, high = (1, 500) if field == 'scale' else (-100, 100)
                if not low <= value <= high: raise ValueError('Image layout exceeds desktop tool limits')
        for field in ("video_list", "video_folder"):
            if field in mod: safe_path(mod[field])
        if ("video_list" in mod) != ("video_folder" in mod): raise ValueError("Incomplete video specification")
        if "video_folder" in mod:
            if mod['video_list'] not in files: raise ValueError('Video list must be a declared payload file')
            if mod["video_folder"].casefold() in {"scripts", "settings.lua", "settings.json", "enabled.txt"}:
                raise ValueError("Video folder conflicts with mod code")
    return mods


class Snapshot:
    def __init__(self, revision, files):
        if not isinstance(revision, str) or not revision or len(revision) > 128: raise ValueError("Invalid revision")
        for name, data in files.items():
            safe_path(name)
            if not isinstance(data, bytes) or len(data) > MAX_FILE: raise ValueError("Invalid or oversized payload")
        if "catalog.json" not in files: raise ValueError("Snapshot has no catalog.json")
        self._mods = _catalogue(files["catalog.json"])
        required = ["catalog.json"] + ["Mods/%s/%s" % (mod["id"], path) for mod in self._mods for path in mod["files"]]
        if any(name not in files for name in required): raise ValueError("Snapshot is missing declared payloads")
        self.files = MappingProxyType({name: files[name] for name in required})
        self.revision = revision

    @property
    def mods(self):
        return copy.deepcopy(self._mods)

    @classmethod
    def from_directory(cls, root):
        root = Path(root)
        def read(name):
            path = root / name
            if any(is_redirect(p) for p in [path] + list(path.parents)):
                raise ValueError("Symbolic links are not allowed")
            if path.stat().st_size > MAX_FILE: raise ValueError("Oversized payload")
            return path.read_bytes()
        files = {"catalog.json": read("catalog.json")}
        for mod in _catalogue(files["catalog.json"]):
            for relative in mod["files"]:
                name = "Mods/%s/%s" % (mod["id"], relative); files[name] = read(name)
        revision = "local-" + hashlib.sha256(b"".join(files.values())).hexdigest()[:16]
        return cls(revision, files)


def read_archive(data, strip_root=True):
    if len(data) > MAX_DOWNLOAD: raise ValueError("Archive download is too large")
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            members = archive.infolist()
            if len(members) > 20000: raise ValueError("Too many archive members")
            seen = set(); total = 0; names = []; spellings = {}
            for entry in members:
                if entry.orig_filename != entry.filename: raise ValueError("Archive path contains platform-normalized characters")
                name = entry.filename.rstrip("/") if entry.is_dir() else entry.filename
                safe_path(name)
                parts = name.split("/")
                for count in range(1, len(parts) + 1):
                    prefix_path = "/".join(parts[:count]); folded = prefix_path.casefold()
                    if folded in spellings and spellings[folded] != prefix_path: raise ValueError("Case-colliding archive directories")
                    spellings[folded] = prefix_path
                if name.casefold() in seen: raise ValueError("Duplicate archive path")
                seen.add(name.casefold())
                if stat.S_ISLNK(entry.external_attr >> 16): raise ValueError("Archive contains symlinks")
                if entry.file_size > MAX_FILE: raise ValueError("Archive file is too large")
                total += entry.file_size
                if total > MAX_EXPANDED: raise ValueError("Expanded archive is too large")
                names.append((entry, name))
            prefix = ""
            if strip_root:
                roots = {name.split("/")[0] for _, name in names}
                if len(roots) != 1 or any("/" not in name and not e.is_dir() for e, name in names): raise ValueError("Archive must have one repository root")
                prefix = next(iter(roots)) + "/"
            output = {}
            for entry, name in names:
                if entry.is_dir(): continue
                name = name[len(prefix):]
                safe_path(name)
                output[name] = archive.read(entry)
            # A file cannot also be the parent directory of another file.
            lowered = {n.casefold() for n in output}
            for name in output:
                if any(str(p).casefold() in lowered for p in PurePosixPath(name).parents if str(p) != "."):
                    raise ValueError("Archive file/directory collision")
            return output
    except (zipfile.BadZipFile, RuntimeError) as exc: raise ValueError("Invalid ZIP archive") from exc


def download(url, limit=MAX_DOWNLOAD):
    if urlparse(url).scheme != "https": raise ValueError("HTTPS download required")
    with urlopen(Request(url, headers={"User-Agent": "PUKEY-Mod-Manager", "Accept": "application/vnd.github+json"}), timeout=30) as response:
        data = response.read(limit + 1)
        if len(data) > limit: raise ValueError("Download exceeds size limit")
        return data


def fetch_latest(cache_dir, progress=None):
    if progress: progress("Resolving the latest catalogue…")
    result = parse_json(download("https://api.github.com/repos/" + REPOSITORY + "/commits/main", 1024 * 1024))
    sha = result.get("sha", "")
    if not re.fullmatch(r"[0-9a-f]{40}", sha): raise ValueError("GitHub returned an invalid commit")
    if progress: progress("Downloading catalogue and mod files…")
    data = download("https://codeload.github.com/" + REPOSITORY + "/zip/" + sha)
    snapshot = Snapshot(sha, read_archive(data))
    cache_dir = Path(cache_dir); cache_dir.mkdir(parents=True, exist_ok=True)
    payload = json.dumps({"revision": sha, "archive": data.hex()}).encode()
    fd, temporary = tempfile.mkstemp(prefix="snapshot-", dir=cache_dir)
    try:
        with os.fdopen(fd, "wb") as stream: stream.write(payload)
        os.replace(temporary, cache_dir / "snapshot.json")
    finally:
        if os.path.exists(temporary): os.unlink(temporary)
    return snapshot


def load_cached(cache_dir):
    path = Path(cache_dir) / "snapshot.json"
    if path.stat().st_size > MAX_DOWNLOAD * 2 + 4096: raise ValueError("Cached snapshot is too large")
    record = parse_json(path.read_bytes())
    if not isinstance(record, dict) or not re.fullmatch(r"[0-9a-f]{40}", record.get("revision", "")): raise ValueError("Invalid cached revision")
    try: data = bytes.fromhex(record["archive"])
    except (KeyError, TypeError, ValueError) as exc: raise ValueError("Invalid cached archive") from exc
    return Snapshot(record["revision"], read_archive(data))
