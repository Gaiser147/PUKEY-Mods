class NativeDecoderTests(unittest.TestCase):
    def setUp(self):
        self.decoder = importlib.import_module('manager.native_decoder')

    def test_rejects_invalid_sizes_before_loading_native_code(self):
        for size in (0, -1, 64 * 1024 * 1024 + 1):
            with self.subTest(size=size), self.assertRaises(ValueError):
                self.decoder.decompress_oodle(b'\x4c\x06a', size)
        for size in (True, 1.5, '1'):
            with self.subTest(size=size), self.assertRaises(TypeError):
                self.decoder.decompress_oodle(b'\x4c\x06a', size)

    def test_rejects_empty_oversized_or_non_bytes_input(self):
        for data in (b'', b'x' * (64 * 1024 * 1024 + 1)):
            with self.subTest(length=len(data)), self.assertRaises(ValueError):
                self.decoder.decompress_oodle(data, 1)
        for data in ('data', bytearray(b'data'), None):
            with self.subTest(type=type(data)), self.assertRaises(TypeError):
                self.decoder.decompress_oodle(data, 1)

    def test_missing_packaged_helper_is_an_actionable_error(self):
        with tempfile.TemporaryDirectory() as directory:
            with patch.object(self.decoder, '_library_path', return_value=Path(directory) / 'missing.dll'):
                self.decoder._load_library.cache_clear()
                with self.assertRaisesRegex(self.decoder.NativeDecoderUnavailable, 'build_ui_decoder'):
                    self.decoder.decompress_oodle(b'\x4c\x06a', 1)
        self.decoder._load_library.cache_clear()

    def test_helper_path_is_inside_package_not_working_directory(self):
        expected_directory = Path(self.decoder.__file__).resolve().parent / 'assets/native'
        self.assertEqual(self.decoder._library_path().parent, expected_directory)
        self.assertIn(self.decoder._library_path().name,
                      ('pukey_ui_decoder.dll', 'libpukey_ui_decoder.so'))


class NativeDecoderIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.decoder = importlib.import_module('manager.native_decoder')
        if not cls.decoder._library_path().is_file():
            if os.environ.get('PUKEY_REQUIRE_NATIVE_DECODER') == '1':
                raise AssertionError('CI requires the compiled native decoder')
            raise unittest.SkipTest('Run python tools/build_ui_decoder.py to build the native helper')

    def test_synthetic_uncompressed_blocks(self):
        # Public Oodle framing; independently generated bytes, matching upstream's
        # documented uncompressed-block regression vector.
        size = 0x40000
        encoded = b'\x4c\x06' + b'\xab' * size + b'\x4c\x06' + b'\xcd' * size
        self.assertEqual(self.decoder.decompress_oodle(encoded, 2 * size),
                         b'\xab' * size + b'\xcd' * size)

    def test_truncated_and_invalid_streams_fail(self):
        for encoded, expected_size in ((b'\x4c\x06short', 100), (b'invalid', 10)):
            with self.subTest(encoded=encoded), self.assertRaises(self.decoder.NativeDecoderError):
                self.decoder.decompress_oodle(encoded, expected_size)

    def test_native_abi_rejects_invalid_sizes_without_dereferencing(self):
        library = self.decoder._load_library()
        written = ctypes.c_size_t(123)
        status = library.pukey_ui_decompress(None, 1, None, 1, ctypes.byref(written))
        self.assertNotEqual(status, 0)
        self.assertEqual(written.value, 0)
        byte = ctypes.c_ubyte(0)
        status = library.pukey_ui_decompress(ctypes.byref(byte), 1, ctypes.byref(byte),
                                             64 * 1024 * 1024 + 1, ctypes.byref(written))
        self.assertNotEqual(status, 0)


class NativeDecoderBuildTests(unittest.TestCase):
    def test_pinned_dependency_without_bundled_license_retains_upstream_terms(self):
        from tools.build_ui_decoder import collect_licenses
        root = Path(__file__).resolve().parents[1]
        with tempfile.TemporaryDirectory() as directory:
            crate = Path(directory) / 'valuable'
            crate.mkdir()
            destination = Path(directory) / 'licenses'
            collect_licenses(root, [{'name': 'valuable', 'version': '0.1.1',
                                    'source': 'registry+example', 'license': 'MIT',
                                    'manifest_path': str(crate / 'Cargo.toml')}], destination)
            license_text = (destination / 'valuable-0.1.1/LICENSE').read_text()
            self.assertIn('Copyright (c) 2021 Valuable Contributors', license_text)
            self.assertTrue((destination / 'Rust-LICENSE-MIT').is_file())
            self.assertTrue((destination / 'Rust-LICENSE-APACHE').is_file())

    def test_bundle_rejects_legacy_game_artwork(self):
        from tools.build_manager import reject_bundled_game_artwork
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            reject_bundled_game_artwork(root)
            artwork = root / 'manager/assets/game'
            artwork.mkdir(parents=True)
            (artwork / 'dialogue.png').write_bytes(b'game artwork')
            with self.assertRaisesRegex(RuntimeError, 'game artwork'):
                reject_bundled_game_artwork(root)

    def test_build_packages_the_helper_and_dependency_license(self):
        from tools.build_ui_decoder import build_decoder
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            crate = root / 'dependency'
            crate.mkdir()
            (crate / 'LICENSE').write_text('Synthetic dependency license', encoding='utf-8')
            (root / 'native/ui_decoder').mkdir(parents=True)
            (root / 'native/ui_decoder/licenses').mkdir()
            (root / 'native/ui_decoder/THIRD-PARTY.md').write_text('Attribution', encoding='utf-8')
            metadata = {'packages': [{'name': 'example', 'version': '1.0.0', 'source': 'registry+example',
                                     'manifest_path': str(crate / 'Cargo.toml'), 'license': 'MIT'}]}
            commands = []

            def cargo_run(command, **options):
                commands.append(command)
                if 'build' in command:
                    output = Path(options['env']['CARGO_TARGET_DIR']) / 'x86_64-pc-windows-msvc/release'
                    output.mkdir(parents=True)
                    (output / 'pukey_ui_decoder.dll').write_bytes(b'synthetic helper')
                return subprocess.CompletedProcess(command, 0, stdout=json.dumps(metadata))

            with patch('tools.build_ui_decoder.subprocess.run', side_effect=cargo_run), \
                    patch('tools.build_ui_decoder.sys.platform', 'win32'):
                output = build_decoder(root, cargo='fake-cargo')
            self.assertEqual(output.read_bytes(), b'synthetic helper')
            licenses = output.parent / 'licenses'
            self.assertEqual((licenses / 'example-1.0.0/LICENSE').read_text(),
                             'Synthetic dependency license')
            self.assertTrue(any('build' in command and '--release' in command and '--locked' in command
                                for command in commands))


if __name__ == '__main__':
    unittest.main()
